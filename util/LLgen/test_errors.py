"""LLgen output and error regressions; set LLGEN to test an alternate executable.

Build util/LLgen/+LLgen, then run:
    python3 -m unittest discover -s util/LLgen -p test_errors.py
"""

import os
from pathlib import Path
import subprocess
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[2]


class ErrorCleanupTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.executable = Path(os.environ.get(
            "LLGEN", ROOT / ".obj/util/LLgen/+LLgen/LLgen")).resolve()
        if not cls.executable.is_file():
            raise unittest.SkipTest("build util/LLgen/+LLgen first, or set LLGEN")

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="llgen-error-test-")
        self.addCleanup(self.temporary.cleanup)
        self.work = Path(self.temporary.name)
        self.tmp = self.work / "tmp"
        self.tmp.mkdir()
        self.out = self.work / "out"
        self.out.mkdir()
        (self.work / "input.g").write_text("%start parse, start;\nstart: 'x';\n")
        self.env = os.environ.copy()
        self.env.update(TMP=str(self.tmp), LLGEN_LIB_DIR=str(ROOT / "util/LLgen/lib"))

    def run_llgen(self, *options, source="input.g", output=None):
        sources = [source] if isinstance(source, str) else list(source)
        result = subprocess.run(
            [str(self.executable), "-w", *options,
             "-o" + str(output if output is not None else self.out), *sources],
            cwd=self.work, env=self.env, capture_output=True, text=True)
        self.assertEqual(list(self.tmp.iterdir()), [], result.stderr)
        return result

    def assert_fatal(self, result, diagnostic):
        # A signal (e.g. SIGABRT from a double fclose) is a negative return code.
        self.assertEqual(result.returncode, 1, result.stderr)
        self.assertIn(diagnostic, result.stderr)

    def test_missing_output_directory(self):
        result = self.run_llgen(output=self.work / "missing")
        self.assert_fatal(result, "Cannot open output file")

    def test_overwrites_existing_outputs_without_identification_checks(self):
        for filename, options in (("input.c", ()), ("Lpars.h", ()),
                                  ("Lpars.c", ()), ("Lncor.c", ("-n",))):
            with self.subTest(filename=filename):
                # Keep each failure independent of files generated by earlier cases.
                for path in self.out.iterdir():
                    path.unlink()
                target = self.out / filename
                target.write_text("This is not generated by LLgen.\n")
                result = self.run_llgen(*options)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertTrue(target.read_text().startswith("/* LLgen generated code"))

    def test_missing_input_file(self):
        self.assert_fatal(self.run_llgen(source="missing.g"), "Cannot open missing.g")

    def test_invalid_grammar(self):
        (self.work / "input.g").write_text("start: 'x';\n")
        self.assert_fatal(self.run_llgen(), "Missing %start")

    def test_temporary_file_creation_failure(self):
        self.env["TMP"] = str(self.work / "missing")
        self.assert_fatal(self.run_llgen(), "Cannot create temporary file")

    def test_successful_generation(self):
        for options in ((), ("-n",)):
            with self.subTest(options=options):
                result = self.run_llgen(*options)
                self.assertEqual(result.returncode, 0, result.stderr)
                for filename in ("input.c", "Lpars.h", "Lpars.c"):
                    self.assertTrue((self.out / filename).is_file(), filename)

    def test_reports_outputs_on_every_run(self):
        result = self.run_llgen()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(set(result.stderr.splitlines()),
                         {str(self.out / filename)
                          for filename in ("input.c", "Lpars.h", "Lpars.c")})
        result = self.run_llgen()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(set(result.stderr.splitlines()),
                         {str(self.out / filename)
                          for filename in ("input.c", "Lpars.h", "Lpars.c")})

    def test_reports_verbose_output_file(self):
        result = self.run_llgen("-v")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn(str(self.out / "LL.output"), result.stderr.splitlines())
        self.assertTrue((self.out / "LL.output").is_file())

    def test_all_outputs_use_relative_directory_and_custom_prefix(self):
        (self.work / "input.g").write_text(
            "%prefix Custom;\n%start parse, start;\nstart: 'x';\n")
        output = Path("relative") / "nested"
        (self.work / output).mkdir(parents=True)
        result = self.run_llgen("-n", "-v", output=output)
        self.assertEqual(result.returncode, 0, result.stderr)
        names = {"input.c", "Custompars.h", "Custompars.c", "Customncor.c", "Custom.output"}
        self.assertEqual({p.name for p in (self.work / output).iterdir()}, names)
        self.assertEqual(list(self.work.glob("*.c")), [])
        self.assertEqual(list(self.work.glob("*.h")), [])
        for name in names:
            self.assertIn(str(output / name), result.stderr.splitlines())

    def test_default_directory(self):
        result = self.run_llgen(output=".")
        self.assertEqual(result.returncode, 0, result.stderr)
        for name in ("input.c", "Lpars.h", "Lpars.c"):
            self.assertTrue((self.work / name).is_file(), name)

    def test_multiple_input_files_use_output_directory(self):
        (self.work / "tokens.g").write_text("%token TOKEN;\n")
        (self.work / "input.g").write_text("%start parse, start;\nstart: TOKEN;\n")
        result = self.run_llgen(source=["tokens.g", "input.g"])
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual({p.name for p in self.out.iterdir()},
                         {"tokens.c", "input.c", "Lpars.h", "Lpars.c"})
        self.assertEqual(list(self.work.glob("*.c")), [])

    def test_late_output_open_failure_exits_cleanly(self):
        (self.out / "Lpars.h").mkdir()
        result = self.run_llgen()
        self.assert_fatal(result, "Cannot open output file")
        self.assertTrue((self.out / "input.c").is_file())

    @unittest.skipUnless(Path("/dev/full").exists(), "requires /dev/full")
    def test_output_write_failure_exits_cleanly(self):
        for filename, options in (("input.c", ()), ("Lpars.h", ()),
                                  ("Lpars.c", ()), ("Lncor.c", ("-n",)),
                                  ("LL.output", ("-vvv",))):
            with self.subTest(filename=filename):
                for path in self.out.iterdir():
                    path.unlink()
                (self.out / filename).symlink_to("/dev/full")
                self.assert_fatal(self.run_llgen(*options), "Write error on output")


if __name__ == "__main__":
    unittest.main()
